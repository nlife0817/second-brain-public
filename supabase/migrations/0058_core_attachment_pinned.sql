-- ============================================================================
-- Вложение, которое приложили нарочно.
--
-- Уборка осиротевших файлов (`purgeOrphanAttachments`) исходит из того, что
-- вложение всегда упомянуто в разметке: картинку вставляют в текст, файл —
-- карточкой. Всё, на что через сутки нет ссылки, считается мусором и сносится.
--
-- С импортом (миграция 0057) появился первый случай, когда это неверно:
-- исходный .xlsx или .docx лежит рядом с узлом как доказательство и как способ
-- скачать первоисточник байт-в-байт, но в теле на него ссылок нет — у книги
-- тело вообще JSON. Без отметки такой файл исчезал бы ровно через сутки после
-- загрузки, причём молча.
--
-- Отметка, а не исключение по виду узла: «файл приложили нарочно» — свойство
-- самого файла, и оно одинаково верно для книги и для документа из Word.
--
-- Совместимо с работающим кодом: колонка добавляется со значением по умолчанию,
-- старый код её не пишет и не читает. Помеченных строк до выката не существует,
-- поэтому и старая уборка ничего лишнего не снесёт.
-- ============================================================================

alter table core.attachments
  add column pinned boolean not null default false;

comment on column core.attachments.pinned is
  'Файл приложен нарочно и не убирается как осиротевший (исходник импорта).';
