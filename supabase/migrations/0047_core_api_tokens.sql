-- ============================================================================
-- Доступ по токену и пометка источника действия.
--
-- 1. core.api_tokens — персональные токены доступа. Нужны интеграциям, которые
--    ходят без сессии-cookie: первая из них — MCP-сервер (/api/mcp), через
--    который с трекером работает Claude.
--
--    Токен принадлежит ЧЕЛОВЕКУ и одной организации. Прав своих у него нет
--    вовсе: запрос собирает тот же AuthContext, что и обычная сессия владельца,
--    и проходит тот же policy-слой. Отсюда два следствия. Первое: отзыв
--    членства владельца закрывает и токен, отдельно чистить нечего. Второе:
--    расследование инцидента остаётся возможным — actor_id события указывает на
--    человека, который имел право это сделать.
--
--    Хранится только sha256 самого значения: дамп базы не должен содержать
--    действующих ключей. prefix — первые символы для опознания строки в списке.
--    scope: 'read' — токен не допускается ни до одной мутации; 'full' — права
--    владельца целиком.
--
-- 2. source у событий и комментариев — чем сделано действие. NULL (и он же
--    умолчание) означает «руками в интерфейсе», иначе метка канала: 'claude'.
--    Колонка нужна именно в БД, а не в payload: лента, инбокс и вебхуки читают
--    события напрямую, и признак «это сделал не человек за экраном» обязан
--    доезжать до каждого из них одинаково. У комментария своя копия по той же
--    причине — тело комментария рисуется мимо ленты.
--
-- Совместимость с работающим кодом: файл только добавляет. Колонки приходят
-- nullable, таблица новая — минуту-другую до перезапуска приложения старый код
-- работает как прежде (он перечисляет колонки явно).
--
-- Таблица закрыта RLS без политик: приложение ходит ролью-владельцем, прямого
-- доступа с клиента нет (см. правило про RLS в src/lib/core/CLAUDE.md).
-- ============================================================================

create table core.api_tokens (
  id           uuid primary key default gen_random_uuid(),
  org_id       uuid not null references core.organizations(id) on delete cascade,
  user_id      uuid not null references core.users(id) on delete cascade,
  name         text not null,
  -- sha256(hex) от значения токена. unique — и защита от коллизии, и индекс,
  -- по которому идёт проверка на каждом запросе.
  token_hash   text not null unique,
  prefix       text not null default '',
  scope        text not null default 'full' check (scope in ('read', 'full')),
  created_at   timestamptz not null default now(),
  last_used_at timestamptz,
  revoked_at   timestamptz
);
alter table core.api_tokens enable row level security;

-- Список токенов организации: свои показываем всем, чужие — администратору.
create index idx_core_api_tokens_org on core.api_tokens (org_id, user_id, created_at desc);

alter table core.events add column if not exists source text;
alter table core.comments add column if not exists source text;
