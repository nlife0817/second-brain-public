-- ============================================================================
-- Позиции статусов приводятся к порядку категорий.
--
-- Было: `position` считался по всему справочнику (`max(position) + 1` на
-- вставке), поэтому статус, добавленный после «Архива», получал позицию больше
-- архивной. Экран настроек раскладывает статусы по категориям и показывал
-- правильную картину, а всё, что идёт по `position` — выпадающие списки,
-- колонки доски, группировка таблицы, гант — показывало «Архив» посреди
-- рабочих статусов. В проде так и было: archived на позиции 6, два in_progress
-- и один done — на 7, 8, 9.
--
-- Стало: `position` пронумерован 1..N в порядке категорий (backlog →
-- in_progress → done → archived), внутри категории — прежний относительный
-- порядок. Дальше это держит код: вставка нового статуса встаёт в конец своей
-- категории, а перетаскивание в настройках перенумеровывает справочник целиком
-- (`reorderStatuses`).
--
-- Совместимо с работающим кодом: меняются только числа в `position`, форма
-- таблицы та же. Категорию не трогаем, поэтому зеркало `kind` под триггером
-- из 0041 остаётся нетронутым.
-- ============================================================================

with ranked as (
  select id,
         row_number() over (
           partition by org_id
           order by array_position(
                      array['backlog', 'in_progress', 'done', 'archived'],
                      category
                    ),
                    position,
                    created_at
         ) as rn
    from core.task_statuses
)
update core.task_statuses s
   set position = ranked.rn
  from ranked
 where ranked.id = s.id
   and s.position is distinct from ranked.rn;
