-- ============================================================================
-- Дата работы: день, на который задачу берут в работу.
--
-- Третья дата задачи, и все три отвечают на разные вопросы:
--   * due_date     — когда должно быть готово (обязательство, о нём напоминания);
--   * start_date   — левая граница полосы на ганте (план проекта, виден команде);
--   * planned_date — когда я этим занимаюсь (личное расписание дня).
--
-- До сих пор третьего вопроса задать было нечем: из пяти задач с дедлайном в
-- пятницу две берут сегодня, три завтра, а фильтр по дедлайну их не различает.
--
-- Дата, а не булев признак «Сегодня»: флаг не сбрасывается сам, и к среде
-- половина списка помечена ещё со вторника. Дата стареет честно — вчерашний
-- невыполненный план виден отдельной группой «Просрочен план», и «беру завтра»
-- ставится тем же полем, без второй сущности.
--
-- Времени у неё нет намеренно: план дня — это «сегодня занимаюсь», а не «в
-- 14:30». Часы уже есть у срока (due_time — напоминания) и у начала (start_time
-- — отрезок в календаре).
--
-- Индекса нет: отбор и сортировка сводного списка считаются на клиенте по уже
-- загруженному набору (см. lib/core/views.ts), в SQL по этой колонке никто не
-- ищет.
-- ============================================================================

ALTER TABLE core.tasks ADD COLUMN IF NOT EXISTS planned_date date;
