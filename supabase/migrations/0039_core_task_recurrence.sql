-- ============================================================================
-- Повтор переезжает внутрь задачи.
--
-- Правило было отдельной сущностью с копией полей задачи (название, проект,
-- исполнители) и своим экраном. Теперь оно привязывается к самой задаче:
-- шаблон новой задачи берётся из живой строки на момент срабатывания, а не из
-- слепка, снятого когда-то в отдельной форме.
--
-- Совместимо с текущим кодом: колонка добавляется nullable, старые правила
-- (task_id is null) продолжают материализоваться по своему `template`.
-- ============================================================================

alter table core.recurring_rules
  add column if not exists task_id uuid references core.tasks(id) on delete cascade;

-- Одна задача — одно расписание: карточка правит его, а не заводит второе.
create unique index if not exists idx_core_recurring_task
  on core.recurring_rules (task_id)
  where task_id is not null;
