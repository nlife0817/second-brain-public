-- ============================================================================
-- Таблицы в базе знаний.
--
-- Третий вид узла рядом с документом и папкой: `kind = 'sheet'`. Отдельной
-- таблицы под книгу нет — по той же причине, по какой её нет у папки (0056):
-- дерево, доступ, перенос, корзина, история версий и привязка к задачам уже
-- написаны вокруг `core.kb_documents`, и вторая их копия разошлась бы с первой
-- на первой же правке.
--
-- Книга лежит в той же колонке `body`, что и HTML документа, но JSON'ом
-- (формат — src/lib/core/sheet/model.ts). Колонка `text`, разбирает и проверяет
-- её приложение: класть книгу в `jsonb` смысла нет — по ней не ищут и не
-- фильтруют, а `jsonb` переупорядочивает ключи и раздувает хранение.
-- Побочная выгода такого решения: история версий работает для таблиц без
-- единой правки — `kb_document_versions.body` тоже `text`.
--
-- Совместимо с работающим кодом: старый код о значении 'sheet' не знает, но и
-- не пишет его; расширение check-констрейнта существующие строки не трогает.
-- ============================================================================

-- Констрейнт из 0056 объявлен инлайном, поэтому имя ему дал Postgres. Снимаем
-- по описанию, а не по имени: на разных базах оно может отличаться.
do $$
declare c record;
begin
  for c in
    select conname
    from pg_constraint
    where conrelid = 'core.kb_documents'::regclass
      and contype = 'c'
      and pg_get_constraintdef(oid) ilike '%kind%'
  loop
    execute format('alter table core.kb_documents drop constraint %I', c.conname);
  end loop;
end $$;

alter table core.kb_documents
  add constraint kb_documents_kind_ck check (kind in ('document', 'folder', 'sheet'));
