-- ============================================================================
-- Ответы на комментарии задачи.
--
-- Иерархия одноуровневая — как в core.doc_comments: ответ крепится к корню
-- обсуждения, а ответ на ответ приложение приводит к тому же корню. Дерево
-- произвольной глубины в узкой колонке карточки нечитаемо, а «корень, под ним
-- ответы по времени» ей ровно подходит.
--
-- Совместимость с работающим кодом: колонка добавляется nullable и без
-- бэкфилла. Старый код перечисляет колонки явно (COMMENT_SELECT в
-- lib/core/comments.ts) и вставляет строки без parent_id — плоская лента
-- продолжает работать те минуты, пока приложение ещё не перезапущено.
-- ============================================================================

alter table core.comments
  add column parent_id uuid references core.comments(id) on delete cascade;

-- Ответы читаются лентой корня; индекс нужен и внешнему ключу для каскада.
create index idx_core_comments_parent on core.comments (parent_id, created_at);
