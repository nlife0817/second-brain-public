// Правка задачи, о которой карточка сообщает экрану-родителю.
//
// Зачем: раньше карточка умела сказать только «что-то изменилось», и каждый
// экран отвечал на это полным перечитыванием своего списка. Смена статуса
// стоила двух последовательных походов на сервер — правки и выборки сотен
// задач заново, — хотя менялась одна строка, и её новое состояние уже пришло
// в ответе на правку.

import type { TaskDetail } from "./types";

export type TaskChange =
  /**
   * Задача изменилась, её актуальное состояние — в `task`. Приходит дважды:
   * сразу по нажатию (`confirmed: false`, предсказание) и после ответа сервера
   * (`confirmed: true`). Побочную работу — обновление счётчиков в сайдбаре и
   * прочие запросы — вешать только на подтверждённую.
   */
  | { type: "patched"; task: TaskDetail; confirmed: boolean }
  | { type: "deleted"; taskId: string }
  /** В списках появилась новая задача (подзадача) — нужен полный перечит. */
  | { type: "reload" };

/**
 * Применяет правку к списку экрана.
 *
 * Возвращает `null`, когда обойтись местной правкой нельзя и список надо
 * перечитать — вызывающий код сам решает, как именно.
 */
export function applyTaskChange<T extends { id: string }>(
  list: T[],
  change: TaskChange,
): T[] | null {
  if (change.type === "reload") return null;
  if (change.type === "deleted") return list.filter((t) => t.id !== change.taskId);
  return list.map((t) => (t.id === change.task.id ? { ...t, ...change.task } : t));
}
