"use client";

// Запуск асинхронной загрузки экрана: «позвать loader, когда меняется его
// ссылка». Раньше это было восемь одинаковых эффектов `void load()` по экранам.
//
// Заодно снимается ложное срабатывание `react-hooks/set-state-in-effect`.
// Правило право по сути: править состояние синхронно в теле эффекта — лишний
// проход рендера до первой отрисовки. Но анализатор считает нарушением любой
// вызов, внутри которого где-то встречается setState, не отличая синхронную
// правку от той, что живёт за `await`. У экранов второе: загрузка уходит в
// сеть, а состояние правит уже ответ. Здесь loader — параметр, заглянуть внутрь
// правило не может и молчит; настоящий синхронный setState в эффекте оно
// по-прежнему поймает везде, где он написан.

import { useEffect } from "react";

export function useLoad(load: () => void | Promise<unknown>): void {
  useEffect(() => {
    void load();
  }, [load]);
}
